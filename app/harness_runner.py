PLUGIN_SRC = ROOT / "plugins" / "opencode" / "sandbox-gate.ts"
PLUGIN_JS_SRC = ROOT / "plugins" / "opencode" / "sandbox-gate.js"


def _copy_plugin(worktree: Path, worker_id: str, ticket_id: str) -> None:
    dest_dir = worktree / ".opencode" / "plugins"
    dest_dir.mkdir(parents=True, exist_ok=True)
    if PLUGIN_SRC.exists():
        text = PLUGIN_SRC.read_text()
    else:
        text = ""
    stamp = (
        f"// worker_id={worker_id}\n"
        f"// ticket_id={ticket_id}\n"
        f"// worktree_path={worktree}\n"
        f"// gate_url=http://127.0.0.1:{settings.port}/api/permission-gate\n"
    )
    # Keep a copy in the worktree for inspection, but put it outside the
    # auto-discovered .opencode/plugins/*.ts path so we do not double-hook.
    inspect_dir = worktree / ".orca-pod"
    inspect_dir.mkdir(parents=True, exist_ok=True)
    if text:
        (inspect_dir / "sandbox-gate.ts").write_text(stamp + text)
    # OpenCode 2 reliably loads global ~/.config/opencode/plugins/*.js
    js_src = PLUGIN_JS_SRC if PLUGIN_JS_SRC.exists() else None
    if js_src:
        (inspect_dir / "sandbox-gate.js").write_text(stamp + js_src.read_text())
        global_dir = Path.home() / ".config" / "opencode" / "plugins"
        global_dir.mkdir(parents=True, exist_ok=True)
        (global_dir / "orca-sandbox-gate.js").write_text(js_src.read_text())
    cfg = worktree / "opencode.json"
    if not cfg.exists():
        cfg.write_text(json.dumps({"$schema": "https://opencode.ai/config.json"}, indent=2))


def _mark_busy(worker: Worker, ticket: Ticket) -> None:
    worker.status = "busy"
    worker.current_ticket_id = ticket.id
    worker.last_heartbeat = now_iso()
    save_worker(worker)
    ticket.status = "in-progress" if ticket.status in {"backlog", "to-do", "planning"} else ticket.status
    if ticket.status == "backlog":
        ticket.status = "to-do"
    if ticket.status == "to-do":
        ticket.status = "planning"
        ticket.status = "in-progress"
    ticket.updated_at = now_iso()
    save_ticket(ticket)


def _finish(worker_id: str, ticket_id: str, ok: bool, message: str) -> None:
    worker = get_worker(worker_id)
    ticket = load_ticket(ticket_id)
    if ticket:
        append_log(ticket, message)
        if ok and ticket.status == "in-progress":
            ticket.status = "in-review"
            ticket.updated_at = now_iso()
            save_ticket(ticket)
    if worker:
        worker.status = "healthy" if ok else "stalled"
        worker.last_heartbeat = now_iso()
        if ok:
            # Keep assignment so the board row still shows the ticket
            pass
        save_worker(worker)


def _write_prompt(worktree: Path, ticket: Ticket, prompt: str) -> None:
    write_file(worktree, ".ticket-prompt.md", prompt)
    write_file(worktree, f"tickets/{ticket.id}.md", ticket.objective + "\n\n" + ticket.context)


def echo_harness(worker: Worker, ticket: Ticket, prompt: str) -> str:
    """Deterministic, clearly labeled stub used for tests and when no LLM key is usable.

    It still writes real files in the worktree and routes commands through the
    permission gate + sandbox runner (not a fake in-memory exec).
    """
    worktree = Path(worker.worktree_path)
    _write_prompt(worktree, ticket, prompt)
    # Derive a simple python module + test from the objective when possible.
    slug = re.sub(r"[^a-z0-9]+", "_", ticket.title.lower()).strip("_") or "task"
    write_file(
        worktree,
        f"{slug}.py",
        '"""Generated by the labeled echo/stub harness (not a live coding model)."""\n\n'
        "def main() -> str:\n"
        f"    return {ticket.title!r}\n\n"
        "if __name__ == '__main__':\n"
        "    print(main())\n",
    )
    write_file(
        worktree,
        f"test_{slug}.py",
        f"from {slug} import main\n\n\ndef test_main():\n    assert main() == {ticket.title!r}\n",
    )
    write_file(worktree, "README.md", f"# {ticket.title}\n\n{ticket.objective}\n\nHarness: echo/stub\n")
    # Copy attachments already handled by orchestrator
    result = evaluate_and_maybe_exec(
        PermissionIn(worker_id=worker.id, ticket_id=ticket.id, worktree_path=str(worktree), command="python3 -m pytest -q"),
        wait_for_human=True,
    )
    return f"echo-harness finished: {result.message} (exit {result.exit_code})"


def builtin_llm_harness(worker: Worker, ticket: Ticket, prompt: str) -> str:
    """Minimal tool-using agent via the local LLM sidecar on :4000."""
    import httpx

    worktree = Path(worker.worktree_path)
    _write_prompt(worktree, ticket, prompt)
    key_ok = bool(settings.custom_llm_api_key or os.environ.get("OPENROUTER_API_KEY"))
    if not key_ok:
        return echo_harness(worker, ticket, prompt) + " [fell back: no CUSTOM_LLM_API_KEY/OPENROUTER_API_KEY]"

    system = (
        "You are a coding worker in a jailed worktree. You may only touch files in the current directory. "
        "Reply with a single JSON object: {\"action\": \"write\"|\"exec\"|\"done\", \"path\": \"...\", "
        "\"content\": \"...\", \"command\": \"...\", \"comment\": \"...\"}. "
        "Use write to create/update a text file, exec to run a shell command (it will go through a permission gate "
        "and a sandbox), and done when the objective is met. Prefer writing a small Python module and a pytest."
    )
    messages = [
        {"role": "system", "content": system},
        {"role": "user", "content": prompt[:8000]},
    ]
    notes = []
    url = f"http://127.0.0.1:{settings.llm_proxy_port}/v1/chat/completions"
    for step in range(6):
        try:
            with httpx.Client(timeout=90) as client:
                resp = client.post(
                    url,
                    headers={"Authorization": "Bearer sk-sidecar-local", "Content-Type": "application/json"},
                    json={"model": "default", "messages": messages, "temperature": 0.2},
                )
                resp.raise_for_status()
                content = resp.json()["choices"][0]["message"]["content"]
        except Exception as exc:
            notes.append(f"LLM step {step} failed: {exc}")
            break
        messages.append({"role": "assistant", "content": content})
        match = re.search(r"\{.*\}", content, re.S)
        if not match:
            notes.append("LLM did not return JSON; stopping")
            break
        try:
            action = json.loads(match.group(0))
        except json.JSONDecodeError:
            notes.append("Invalid JSON from LLM")
            break
        kind = (action.get("action") or "done").lower()
        if kind == "write" and action.get("path"):
            try:
                write_file(worktree, action["path"], action.get("content") or "")
                obs = f"wrote {action['path']}"
            except Exception as exc:
                obs = f"write failed: {exc}"
            notes.append(obs)
            messages.append({"role": "user", "content": obs})
            continue
        if kind == "exec" and action.get("command"):
            result = evaluate_and_maybe_exec(
                PermissionIn(
                    worker_id=worker.id,
                    ticket_id=ticket.id,
                    worktree_path=str(worktree),
                    command=action["command"],
                )
            )
            obs = f"exec pending={result.pending} exit={result.exit_code} out={(result.output or '')[:1500]}"
            notes.append(obs)
            messages.append({"role": "user", "content": obs})
            if result.pending:
                notes.append("stopped: command is waiting on the permission gate")
                break
            continue
        notes.append(action.get("comment") or "done")
        break
    else:
        notes.append("reached step budget")
    return "builtin-llm: " + " | ".join(notes)


def opencode_harness(worker: Worker, ticket: Ticket, prompt: str) -> str:
    worktree = Path(worker.worktree_path)
    _copy_plugin(worktree, worker.id, ticket.id)
    _write_prompt(worktree, ticket, prompt)
    binary = shutil.which("opencode")
    if not binary:
        return builtin_llm_harness(worker, ticket, prompt) + " [fell back: opencode binary not on PATH]"
    env = os.environ.copy()
    env["ORCA_POD_WORKER_ID"] = worker.id
    env["ORCA_POD_TICKET_ID"] = ticket.id
    env["ORCA_POD_WORKTREE"] = str(worktree)
    env["ORCA_POD_GATE_URL"] = f"http://127.0.0.1:{settings.port}/api/permission-gate"
    # Harnesses must talk to the sidecar with the dummy token.
    env["OPENAI_BASE_URL"] = f"http://127.0.0.1:{settings.llm_proxy_port}/v1"
    env["OPENAI_API_KEY"] = "sk-sidecar-local"
    # If OpenCode still selects the OpenRouter provider from its global config,
    # give it the live key from ORCA_LLM_API_KEY (never a stale .env value).
    live = (os.environ.get("ORCA_LLM_API_KEY") or os.environ.get("CUSTOM_LLM_API_KEY") or "").strip()
    if live:
        env["OPENROUTER_API_KEY"] = live
        env["OPENROUTER_USER_API_KEY"] = live
    try:
        proc = subprocess.run(
            [binary, "run", "--standalone", "--auto", "--title", ticket.id, prompt],
            cwd=str(worktree),
            capture_output=True,
            text=True,
            timeout=300,
            env=env,
        )
        out = (proc.stdout or "") + "\n" + (proc.stderr or "")
        msg = f"opencode exit {proc.returncode}: {out[-4000:]}"
        if proc.returncode != 0:
            return builtin_llm_harness(worker, ticket, prompt) + f" [fell back after {msg[:240]}]"
        return msg
    except Exception as exc:
        return builtin_llm_harness(worker, ticket, prompt) + f" [fell back: opencode error {exc}]"


def dispatch(worker: Worker, ticket: Ticket, prompt: str) -> None:
    _mark_busy(worker, ticket)
    append_log(ticket, f"Dispatched to {worker.name} ({worker.harness}) in {worker.worktree_path}")

    def run() -> None:
        try:
            if settings.force_echo_harness:
                msg = echo_harness(worker, ticket, prompt)
                label = "echo/stub harness"
            elif worker.harness == "opencode" and not settings.force_echo_harness:
                msg = opencode_harness(worker, ticket, prompt)
                label = "opencode"
            else:
                # pi / deepseek CLIs are optional; use sidecar LLM, clearly labeled.
                msg = builtin_llm_harness(worker, ticket, prompt)
                label = f"{worker.harness} via builtin-llm sidecar"
            _finish(worker.id, ticket.id, ok=True, message=f"[{label}] {msg}")
        except Exception as exc:
            _finish(worker.id, ticket.id, ok=False, message=f"Harness failed: {exc}")

    if settings.sync_dispatch:
        run()
    else:
        threading.Thread(target=run, name=f"harness-{worker.id}", daemon=True).start()
